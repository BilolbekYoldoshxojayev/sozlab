def search_encyclopedia(query: str, limit: int = 3) -> list[dict[str, Any]]:
    """Search legal encyclopedia articles by query words."""
    q = query.lower().strip()
    words = [w for w in q.split() if len(w) > 2]
    
    scored: list[tuple[float, dict[str, Any]]] = []
    for item in LEGAL_ENCYCLOPEDIA_ARTICLES:
        score = 0.0
        # Code match
        if item["code"].lower() in q:
            score += 15.0
        # Keywords
        for kw in item["keywords"]:
            if kw.lower() in q:
                score += 5.0
            for w in words:
                if w in kw.lower():
                    score += 2.0
        # Title and summary
        title_lower = item["title"].lower()
        summary_lower = item["summary"].lower()
        if q in title_lower:
            score += 10.0
        if q in summary_lower:
            score += 5.0
        for w in words:
            if w in title_lower:
                score += 2.0
            if w in summary_lower:
                score += 1.0
                
        if score > 0.0:
            scored.append((score, item))
            
    scored.sort(key=lambda x: x[0], reverse=True)
    return [item for _, item in scored[:limit]]
