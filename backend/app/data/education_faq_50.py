# Quick index by ID
FAQ_BY_ID: Dict[int, Dict[str, Any]] = {item["id"]: item for item in FAQ_50_ITEMS}

def get_faq_by_id(faq_id: int) -> Optional[Dict[str, Any]]:
    """Retrieve FAQ item by exact ID (1-50)."""
    return FAQ_BY_ID.get(faq_id)

def search_faq_items(query: str, limit: int = 5) -> List[Dict[str, Any]]:
    """
    High-accuracy keyword and semantic matcher across all 50 FAQs.
    Normalizes Uzbek Latin characters and scores by field importance.
    """
    if not query or not query.strip():
        return []

    def _normalize(s: str) -> str:
        return s.lower().replace('‘', "'").replace('’', "'").replace('ʻ', "'").replace('ʼ', "'").replace('`', "'")

    q = _normalize(query.strip())
    words = [w for w in re.findall(r'\b[\w\'-]+\b', q) if len(w) > 2]
    
    scored: List[tuple[float, Dict[str, Any]]] = []
    for item in FAQ_50_ITEMS:
        score = 0.0
        q_text = _normalize(item["question"])
        kws = [_normalize(kw) for kw in item["keywords"]]
        legal = _normalize(item.get("legal_basis", ""))
        short_ans = _normalize(item.get("short_answer", ""))
        full_ans = _normalize(item.get("full_answer", ""))
        ch_name = _normalize(item.get("chapter_name", ""))

        # 1. Exact query match in question or keywords
        if q in q_text:
            score += 25.0
        for kw in kws:
            if q == kw:
                score += 20.0
            elif q in kw or kw in q:
                score += 10.0

        # 2. Tokenized word matches
        for w in words:
            for kw in kws:
                if w == kw:
                    score += 6.0
                elif w in kw:
                    score += 3.0
            if w in q_text:
                score += 4.0
            if w in legal:
                score += 2.0
            if w in short_ans:
                score += 2.0
            if w in full_ans:
                score += 1.0
            if w in ch_name:
                score += 1.5

        if score > 0.0:
            scored.append((score, item))

    scored.sort(key=lambda x: x[0], reverse=True)
    return [item for _, item in scored[:limit]]
