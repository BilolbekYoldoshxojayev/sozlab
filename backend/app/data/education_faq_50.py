# Quick index by ID
FAQ_BY_ID: dict[int, dict[str, Any]] = {item["id"]: item for item in FAQ_50_ITEMS}

def search_faq_items(query: str, limit: int = 5) -> list[dict[str, Any]]:
    """Hybrid keyword and semantic matcher over the 50 FAQs."""
    q = query.lower().strip()
    words = [w for w in q.split() if len(w) > 2]
    
    scored: list[tuple[float, dict[str, Any]]] = []
    for item in FAQ_50_ITEMS:
        score = 0.0
        # Direct keyword exact match
        for kw in item["keywords"]:
            if kw.lower() in q:
                score += 5.0
            for w in words:
                if w in kw.lower():
                    score += 2.0
        # Question text match
        q_text = item["question"].lower()
        if q in q_text:
            score += 10.0
        for w in words:
            if w in q_text:
                score += 1.5
        # Legal basis match
        legal_text = item["legal_basis"].lower()
        for w in words:
            if w in legal_text:
                score += 1.0
        # Full answer match
        ans_text = item["full_answer"].lower()
        for w in words:
            if w in ans_text:
                score += 0.5
                
        if score > 0.0:
            scored.append((score, item))
            
    scored.sort(key=lambda x: x[0], reverse=True)
    return [item for _, item in scored[:limit]]
